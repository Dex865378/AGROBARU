const PHRASES = new Map(
  SPANISH_TO_ENGLISH.map(([spanish, english]) => [spanish.trim().toLowerCase(), english]),
);

const PATTERNS: Array<[RegExp, string]> = [
  [/^reseñas \((\d+)\)$/i, 'Reviews ($1)'],
  [/^reseña \((\d+)\)$/i, 'Review ($1)'],
  [/^(\d+) reseñas?$/i, '$1 reviews'],
  [/^(\d+) transacciones escrow completadas$/i, '$1 completed Escrow transactions'],
  [/^(\d+) transacción escrow completada$/i, '$1 completed Escrow transaction'],
  [/^(\d+) lotes?$/i, '$1 batches'],
  [/^(\d+) cajas?$/i, '$1 boxes'],
  [/^publicado:\s*(.+)$/i, 'Published: $1'],
  [/^fotos:\s*(.+)$/i, 'Photos: $1'],
  [/^ver perfil de\s+(.+)$/i, 'View profile of $1'],
  [/^chatear directamente con\s+(.+)$/i, 'Chat directly with $1'],
];

export function translateInterfacePhrase(input: string): string {
  if (!input || !input.trim()) return input;

  const leading = input.match(/^\s*/)?.[0] || '';
  const trailing = input.match(/\s*$/)?.[0] || '';
  const core = input.slice(leading.length, input.length - trailing.length);
  if (!core) return input;

  const direct = PHRASES.get(core.trim().toLowerCase());
  if (direct) {
    const preserveCase = core === core.toUpperCase() && /[A-ZÁÉÍÓÚÑ]/.test(core);
    return `${leading}${preserveCase ? direct.toUpperCase() : direct}${trailing}`;
  }

  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(core)) {
      return `${leading}${core.replace(pattern, replacement)}${trailing}`;
    }
  }

  return input;
}

/** Evita traducir contenido escrito por usuarios, código o campos editables. */
export function shouldSkipTranslation(node: Node): boolean {
  const parent = node.parentElement;
  if (!parent) return true;
  if (parent.closest('[data-no-translate]')) return true;
  const tag = parent.tagName;
  if (['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'INPUT', 'CODE', 'PRE'].includes(tag)) {
    return true;
  }
  if (parent.isContentEditable) return true;
  return false;
}
